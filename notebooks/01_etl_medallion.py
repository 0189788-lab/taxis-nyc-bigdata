"""Leer Silver"""

from pyspark.sql import functions as F

ruta = "/content/drive/MyDrive/Bigdata/"
silver = spark.read.parquet(ruta + "silver/taxi_trips")
print("Registros Silver:", silver.count())

"""Crear Tablas Gold
1. Viajes e ingresos por hora
"""

gold_hora = (silver.groupBy("hora")
    .agg(F.count("*").alias("total_viajes"),
         F.round(F.avg("fare_amount"), 2).alias("tarifa_promedio"),
         F.round(F.avg("trip_distance"), 2).alias("distancia_promedio"),
         F.round(F.avg("duracion_min"), 2).alias("duracion_promedio_min"))
    .orderBy("hora"))

"""2. Ingresos por Zona de origen"""

gold_zona = (silver.groupBy("borough_origen", "zona_origen")
    .agg(F.count("*").alias("total_viajes"),
         F.round(F.sum("total_amount"), 2).alias("ingreso_total"),
         F.round(F.avg("fare_amount"), 2).alias("tarifa_promedio"))
    .orderBy(F.desc("total_viajes")))

"""3. Propinas por dia de la semana (solo pagos con tarjeta porque en efectivo no la registran)"""

gold_propinas = (silver.filter(F.col("payment_type") == 1)
    .withColumn("dia_num", F.dayofweek("tpep_pickup_datetime"))
    .groupBy("dia_num", "dia_semana")
    .agg(F.count("*").alias("total_viajes"),
         F.round(F.avg("tip_amount"), 2).alias("propina_promedio"),
         F.round(F.avg(F.col("tip_amount") / F.col("fare_amount") * 100), 2).alias("propina_pct"))
    .orderBy("dia_num"))

"""4. Resumen diario (para gráfica de linea de tiempo)"""

gold_diario = (silver.groupBy("fecha")
    .agg(F.count("*").alias("total_viajes"),
         F.round(F.sum("total_amount"), 2).alias("ingreso_total"))
    .orderBy("fecha"))

"""5. Rutas más comunes entre los boroughs"""

gold_rutas = (silver.groupBy("borough_origen", "borough_destino")
    .agg(F.count("*").alias("total_viajes"),
         F.round(F.avg("fare_amount"), 2).alias("tarifa_promedio"))
    .orderBy(F.desc("total_viajes")))

"""6. Método de pago"""

gold_pago = (silver.groupBy("payment_type")
    .agg(F.count("*").alias("total_viajes"))
    .withColumn("metodo",
        F.when(F.col("payment_type") == 1, "Tarjeta")
         .when(F.col("payment_type") == 2, "Efectivo")
         .when(F.col("payment_type") == 3, "Sin cargo")
         .when(F.col("payment_type") == 4, "Disputa")
         .otherwise("Otro")))

"""Revisar y guardar"""

tablas = {
    "viajes_por_hora": gold_hora,
    "ingresos_por_zona": gold_zona,
    "propinas_por_dia": gold_propinas,
    "resumen_diario": gold_diario,
    "rutas_borough": gold_rutas,
    "metodo_pago": gold_pago,
}

for nombre, tabla in tablas.items():
    tabla.show(5, truncate=False)
    tabla.write.mode("overwrite").parquet(ruta + f"gold/{nombre}")
    tabla.toPandas().to_csv(ruta + f"gold/{nombre}.csv", index=False)
    print("Guardada:", nombre)